import { useEffect, type ReactElement } from "react"
import { generateModule } from "../../interface/functions.ts"
import { typedModuleText } from "../../interface/load.ts"
import { NO_DID_HASH, serverResult } from "../../interface/server-result.ts"
import type { CanisterInterface } from "../../interface/types.ts"
import { Code } from "../Code.tsx"
import { safeFileName } from "../download.ts"
import { Notice } from "../Notice.tsx"
import { Spinner } from "../Spinner.tsx"
import { useTask } from "../use-task.ts"

interface ModuleText {
  module: string
  omitted: CanisterInterface["omitted"]
  committed: boolean
}

/**
 * The `@candid-core/schema` TypeScript module for the interface: for a
 * typed canister the committed one, for any other the module `didToModule`
 * writes on the server. Loaded when the tab opens.
 */
export function TypeScriptTab({
  iface,
}: {
  iface: CanisterInterface
}): ReactElement {
  const task = useTask<ModuleText>()
  const { run } = task
  const typedModule =
    iface.source.kind === "typed" ? iface.source.module : undefined
  const didSha256 = iface.didSha256

  useEffect(() => {
    run(async () => {
      if (typedModule !== undefined) {
        return {
          module: await typedModuleText(typedModule),
          omitted: [],
          committed: true,
        }
      }
      if (didSha256 === undefined) throw new Error(NO_DID_HASH)
      const result = await serverResult(
        generateModule({ data: { canisterId: iface.canisterId, didSha256 } })
      )
      if (!result.ok) throw new Error(result.message)
      return {
        module: result.module,
        omitted: result.omitted,
        committed: false,
      }
    })
  }, [run, typedModule, iface.canisterId, didSha256])

  const fileName = `${safeFileName(iface.registry?.module ?? iface.registry?.slug ?? iface.name)}.ts`
  const state = task.state
  return (
    <div className="stack">
      <p className="text-sm muted">
        {typedModule !== undefined
          ? `The module the app imports: src/canisters/${typedModule}.ts, generated by candid-core-cli gen from the committed .did. Its values double as schemas, and type Actor types client.canister().`
          : "What candid-core-cli gen would write for this interface: a type and a schema per Candid type, the service schema actor and type Actor. Save it as a .ts file and call the canister with typed methods."}
      </p>
      {(state.status === "idle" || state.status === "running") && (
        <div className="row text-sm muted">
          <Spinner size="sm" label="Generating the module" />
          <span>
            {typedModule !== undefined
              ? "Loading the committed module…"
              : "Generating the module on the server…"}
          </span>
        </div>
      )}
      {state.status === "failed" && (
        <Notice tone="danger" title="No module">
          <p className="break-all">{state.message}</p>
        </Notice>
      )}
      {state.status === "done" && (
        <>
          {state.value.omitted.length > 0 && (
            <Notice tone="warn" title="Left out of the module">
              <ul className="list-plain stack-xs">
                {state.value.omitted.map((entry) => (
                  <li key={`${entry.kind}:${entry.name}`}>
                    <code className="code-inline">{entry.name}</code>{" "}
                    <span className="muted">
                      ({entry.kind}: {entry.reason}
                      {entry.via === undefined ? "" : `, via ${entry.via}`})
                    </span>
                  </li>
                ))}
              </ul>
            </Notice>
          )}
          <Code
            text={state.value.module}
            label={
              state.value.committed ? "typescript (committed)" : "typescript"
            }
            showSize
            download={{
              filename: fileName,
              type: "text/typescript;charset=utf-8",
            }}
            maxHeight="70vh"
            ariaLabel={`TypeScript module for ${iface.name}`}
          />
        </>
      )}
    </div>
  )
}
